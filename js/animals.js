// =====================================================================
// animals.js — loads and merges every animal batch file.
// To add animals later, add a file name to BATCH_FILES. That is the ONLY edit needed.
// =====================================================================

// ===== BATCH FILES (EDIT HERE) =====
const BATCH_FILES = ["../animals/animals_seed.js", "../animals/animals_aerial.js", "../animals/animals_big_land_carnivores.js", "../animals/animals_herbivores.js", "../animals/animals_herps.js", "../animals/animals_invertebrates.js", "../animals/animals_marine.js"];
// ===== END BATCH FILES =====

async function loadAll() {
  const byId = new Map();
  for (const f of BATCH_FILES) {
    try {
      const mod = await import(f);
      const list = Array.isArray(mod.default) ? mod.default : [];
      for (const a of list) {
        if (!a || typeof a.id !== "string") { console.warn(`[animals] ${f}: entry without id skipped`); continue; }
        if (byId.has(a.id)) { console.warn(`[animals] duplicate id "${a.id}" in ${f} ignored (first one wins)`); continue; }
        byId.set(a.id, a);
      }
    } catch (err) {
      console.warn(`[animals] could not load ${f}, skipping:`, err);
    }
  }
  return [...byId.values()];
}

// Optional silhouettes (generated by tools/fetch_silhouettes.mjs). Missing or broken file = emoji everywhere, nothing else changes.
async function attachSilhouettes(list) {
  try {
    const sil = (await import("./silhouettes.js")).default || {};
    for (const a of list) if (!a.silhouette && sil[a.id] && typeof sil[a.id].url === "string") a.silhouette = sil[a.id].url;
  } catch (err) { console.warn("[animals] silhouettes.js not loaded, using emoji:", err); }
  return list;
}

export const ANIMALS = await attachSilhouettes(await loadAll());
export const ANIMAL_MAP = new Map(ANIMALS.map((a) => [a.id, a]));
